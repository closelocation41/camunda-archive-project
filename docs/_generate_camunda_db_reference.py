def render_table(name: str, meta: dict) -> str:
    display = DISPLAY_NAMES[name]
    lines = [
        "---",
        f"# {display}",
        f"## {name}",
        "### Table Summary",
        "| Property | Description |",
        "| --- | --- |",
        f"| Category | {meta['category']} |",
        f"| Purpose | {meta['purpose']} |",
        f"| When Rows Are Inserted | {meta['insert']} |",
        f"| When Rows Are Updated | {meta['update']} |",
        f"| When Rows Are Deleted | {meta['delete']} |",
        f"| Primary Key | {meta['pk']} |",
        f"| Related Tables | {meta['related']} |",
        "",
        "### Columns",
        "| Column | Data Type | Description |",
        "| --- | --- | --- |",
    ]
    for col, dtype, desc in meta["columns"]:
        lines.append(f"| {col} | {dtype} | {desc} |")
    lines.extend([
        "",
        "### Relationship Summary",
        "| Parent Table | Child Table | Relationship |",
        "| --- | --- | --- |",
    ])
    if meta["relationships"]:
        for parent, child, rel in meta["relationships"]:
            lines.append(f"| {parent} | {child} | {rel} |")
    else:
        lines.append("| — | — | No direct foreign-key relationships. |")
    lines.extend([
        "",
        "### Common Use Cases",
        "| Use Case | Description |",
        "| --- | --- |",
    ])
    for use_case, desc in meta["use_cases"]:
        lines.append(f"| {use_case} | {desc} |")
    lines.append("")
    return "\n".join(lines)


def generate_markdown() -> str:
    parts = [
        "# Camunda 7 Database Reference",
        "",
        f"Reference guide for all Camunda Platform 7 database tables based on the "
        f"**{SCHEMA_VERSION} PostgreSQL schema**.",
        "",
        "> **Note:** `ACT_RU_TIMER_JOB`, `ACT_RU_SUSPENDED_JOB`, and `ACT_RU_DEADLETTER_JOB` "
        "are **not** separate tables in Camunda 7. All job types (async, timer, suspended, "
        "deadletter) are stored in `ACT_RU_JOB`, distinguished by the `TYPE_` and "
        "`SUSPENSION_STATE_` columns.",
        "",
        "> **Note:** `ACT_RE_MODEL` is a legacy Activiti table and is **not** part of the "
        "Camunda 7 database schema.",
        "",
        "## Table of Contents",
        "",
    ]
    current_chapter = 0
    for name in TABLE_ORDER:
        meta = TABLES[name]
        ch = meta["chapter"]
        if ch != current_chapter:
            current_chapter = ch
            parts.append(f"### Chapter {ch}: {CHAPTER_TITLES[ch]}")
            parts.append("")
        display = DISPLAY_NAMES[name]
        parts.append(f"- [{display}](#{display.lower().replace(' ', '-')}) (`{name}`)")
    parts.append("")
    current_chapter = 0
    for name in TABLE_ORDER:
        meta = TABLES[name]
        ch = meta["chapter"]
        if ch != current_chapter:
            current_chapter = ch
            parts.extend([
                "---",
                "",
                f"## Chapter {ch}: {CHAPTER_TITLES[ch]}",
                "",
            ])
            if ch == 6:
                parts.extend([
                    "> `ACT_RU_AUTHORIZATION` is a runtime table (prefix `ACT_RU_`) documented "
                    "in this chapter because it governs resource access control across the engine.",
                    "",
                ])
            if ch == 7:
                parts.extend([
                    "> Metrics tables store engine telemetry data with automatic retention-based "
                    "cleanup. They are not linked to process execution entities via foreign keys.",
                    "",
                ])
        parts.append(render_table(name, meta))
    return "\n".join(parts)


